// ---------------------------------------------------------------------------
// The registry. Adding a panel revision is ONE row.
// Timings are GUITION's, per variant.
// ---------------------------------------------------------------------------
const JD9165PanelDef JD9165_PANELS[] = {
    {   "Newer screen",
        "Screens bought recently. Try this first.",
        nullptr, 0,                       // driver's built-in New_Panel table
        52,  24, 136, 160,  2, 21, 12 },

    {   "Older screen",
        "Earlier batch, before the panel was changed.",
        jd9165_init_old,
        (uint16_t)(sizeof(jd9165_init_old) / sizeof(jd9165_init_old[0])),
        52,  20, 160, 160, 10, 23, 12 },
};

const uint8_t JD9165_PANEL_COUNT =
    (uint8_t)(sizeof(JD9165_PANELS) / sizeof(JD9165_PANELS[0]));

uint8_t jd9165PanelClamp(int idx) {
    if (idx < 0 || idx >= (int)JD9165_PANEL_COUNT) return 0;
    return (uint8_t)idx;
}
